    @Transactional
    public void seedDemoDataIfNecessary(User student, User staff) {
        long currentCount = itemRepository.count();
        if (currentCount >= 70) {
            log.info("Database already contains {} items. Skipping demo seeding.", currentCount);
            return;
        }

        log.info("Populating database with 50 unique Lost items, 20 unique Found items, and image-based verification quizzes...");
        
        // Remove existing items and claims to ensure a clean, non-duplicate dataset
        claimRepository.deleteAll();
        quizQuestionRepository.deleteAll();
        itemRepository.deleteAll();

        List<Item> lostItems = create50LostItems(student, staff);
        itemRepository.saveAll(lostItems);
        log.info("Saved 50 unique Lost Items.");

        List<Item> foundItems = create20FoundItems(student, staff);
        for (Item foundItem : foundItems) {
            Item saved = itemRepository.save(foundItem);
            List<QuizQuestion> questions = createQuizForFoundItem(saved);
            quizQuestionRepository.saveAll(questions);
        }
        log.info("Saved 20 unique Found Items with verification quizzes.");

        // Create sample demo claim on found item #2
        if (!foundItems.isEmpty()) {
            Item sampleFound = foundItems.get(1); // Student ID Card
            Claim sampleClaim = Claim.builder()
                    .item(sampleFound)
                    .claimant(student)
                    .proofOfOwnership("This is my classmate Rohan's ID card. Roll number matches CS23045, barcode ending in 7741.")
                    .additionalInfo("He lost it during lunch hour near the billing counter.")
                    .status(Claim.ClaimStatus.PENDING)
                    .build();
            claimRepository.save(sampleClaim);
        }

        log.info("Demo data seeding completed successfully! Total items: {}", itemRepository.count());
    }

